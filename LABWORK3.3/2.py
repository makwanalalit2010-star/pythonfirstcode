'''Q.2
Perform the following operations on the given two sets:
Union
Intersection
Difference

set_a = {1, 2, 3, 4}
set_b = {3, 4, 5, 6}

'''


set_a = {1, 2, 3, 4}
set_b = {3, 4, 5, 6}

print("Union:",set_a.union(set_b))
print("intersection:",set_a.intersection(set_b))
print("diff:",set_a.difference(set_b))

